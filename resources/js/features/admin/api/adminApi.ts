import { deleteJson, downloadFile, getJson, patchJson, postJson, toSearchParams } from '@/lib/api'
import type {
  AdminBatchResponse,
  AdminBatchesResponse,
  AdminCompetitionResponse,
  AdminCompetitionsResponse,
  AdminExamAttemptDetailResponse,
  AdminExamAttemptFilters,
  AdminExamAttemptScoreResponse,
  AdminExamAttemptsResponse,
  AdminExamsResponse,
  AdminExamStagesResponse,
  AdminAdvancementResponse,
  AdminMissingSubmissionFilters,
  AdminMissingSubmissionsResponse,
  AdminSubmissionFilters,
  AdminSubmissionResponse,
  AdminSubmissionReviewPayload,
  AdminSubmissionsResponse,
  AdminOperationFilters,
  AdminOperationResponse,
  AdminOperationsResponse,
  AdminPaymentFilters,
  AdminPaymentResponse,
  AdminPaymentsResponse,
  AdminTeamFilters,
  AdminTeamResponse,
  AdminTeamsResponse,
  AdminTeamUpdatePayload,
  BatchPayload,
  AdminStageResponse,
  AdminStagesResponse,
  AdminStageScoresResponse,
  StagePayload,
  UpdateStagePayload,
  CompetitionFilters,
  CompetitionPayload,
  CreateAdminOperationPayload,
  DeleteResponse,
  ExportPaymentsFilters,
  ExportTeamsFilters,
  TeamRevisionPayload,
} from '../types/adminTypes'

const requestHeaders = () => ({ 'X-Request-ID': crypto.randomUUID() })

export const adminApi = {
  teams: (filters: AdminTeamFilters) => getJson<AdminTeamsResponse>(`/api/admin/teams${toSearchParams(filters)}`),
  exportTeams: (filters: ExportTeamsFilters) => downloadFile(`/api/admin/teams/export${toSearchParams(filters)}`),
  team: (teamId: string) => getJson<AdminTeamResponse>(`/api/admin/teams/${teamId}`),
  verifyTeam: (teamId: string) => postJson<AdminTeamResponse>(`/api/admin/teams/${teamId}/verify`, undefined, { headers: requestHeaders() }),
  reviseTeam: (teamId: string, payload: TeamRevisionPayload) => postJson<AdminTeamResponse>(`/api/admin/teams/${teamId}/revision`, payload, { headers: requestHeaders() }),
  rejectTeam: (teamId: string, reason: string) => postJson<AdminTeamResponse>(`/api/admin/teams/${teamId}/reject`, { reason }, { headers: requestHeaders() }),
  unverifyTeam: (teamId: string, reason?: string) => postJson<AdminTeamResponse>(`/api/admin/teams/${teamId}/unverify`, reason ? { reason } : undefined, { headers: requestHeaders() }),
  updateTeamRegistration: (teamId: string, payload: AdminTeamUpdatePayload) => patchJson<AdminTeamResponse>(`/api/admin/teams/${teamId}/registration`, payload, { headers: requestHeaders() }),
  competitions: (filters: CompetitionFilters) => getJson<AdminCompetitionsResponse>(`/api/competitions${toSearchParams(filters)}`),
  createCompetition: (payload: CompetitionPayload) => postJson<AdminCompetitionResponse>('/api/admin/competitions', payload),
  updateCompetition: (id: string, payload: CompetitionPayload) => patchJson<AdminCompetitionResponse>(`/api/admin/competitions/${id}`, payload),
  deleteCompetition: (id: string) => deleteJson<DeleteResponse>(`/api/admin/competitions/${id}`),
  batches: (competitionId?: string) => getJson<AdminBatchesResponse>(`/api/admin/batches${toSearchParams({ competition_id: competitionId })}`),
  createBatch: (payload: BatchPayload) => postJson<AdminBatchResponse>('/api/admin/batches', payload),
  updateBatch: (id: string, payload: Omit<BatchPayload, 'competition_id'>) => patchJson<AdminBatchResponse>(`/api/admin/batches/${id}`, payload),
  stages: (competitionId?: string) => getJson<AdminStagesResponse>(`/api/admin/stages${toSearchParams({ competition_id: competitionId })}`),
  stageScores: (stageId: string) => getJson<AdminStageScoresResponse>(`/api/admin/stages/${stageId}/scores`),
  stage: (id: string) => getJson<AdminStageResponse>(`/api/admin/stages/${id}`),
  createStage: (payload: StagePayload) => postJson<AdminStageResponse>('/api/admin/stages', payload),
  updateStage: (id: string, payload: UpdateStagePayload) => patchJson<AdminStageResponse>(`/api/admin/stages/${id}`, payload),
  deleteStage: (id: string) => deleteJson<DeleteResponse>(`/api/admin/stages/${id}`),

  deleteBatch: (id: string) => deleteJson<DeleteResponse>(`/api/admin/batches/${id}`),
  payments: (filters: AdminPaymentFilters) => getJson<AdminPaymentsResponse>(`/api/admin/payments${toSearchParams(filters)}`),
  exportPayments: (filters: ExportPaymentsFilters) => downloadFile(`/api/admin/payments/export${toSearchParams(filters)}`),
  payment: (registrationId: string) => getJson<AdminPaymentResponse>(`/api/admin/payments/${registrationId}`),
  verifyPayment: (registrationId: string) => postJson<AdminPaymentResponse>(`/api/admin/registrations/${registrationId}/payment/verify`, undefined, { headers: requestHeaders() }),
  revisePayment: (registrationId: string, reason: string) => postJson<AdminPaymentResponse>(`/api/admin/registrations/${registrationId}/payment/revision`, { reason }, { headers: requestHeaders() }),
  rejectPayment: (registrationId: string, reason: string) => postJson<AdminPaymentResponse>(`/api/admin/registrations/${registrationId}/payment/reject`, { reason }, { headers: requestHeaders() }),
  unverifyPayment: (registrationId: string, reason: string) => postJson<AdminPaymentResponse>(`/api/admin/registrations/${registrationId}/payment/unverify`, { reason }, { headers: requestHeaders() }),

  operations: (filters: AdminOperationFilters) => getJson<AdminOperationsResponse>(`/api/admin/operations${toSearchParams(filters)}`),
  operation: (operationId: string) => getJson<AdminOperationResponse>(`/api/admin/operations/${operationId}`),
  createOperation: (payload: CreateAdminOperationPayload) => postJson<AdminOperationResponse>('/api/admin/operations', payload, { headers: requestHeaders() }),
  retryOperationSpreadsheet: (operationId: string) => postJson<{ queued: number }>(`/api/admin/operations/${operationId}/retry-spreadsheet`, undefined, { headers: requestHeaders() }),

  examStages: () => getJson<AdminExamStagesResponse>('/api/admin/exam-stages'),
  exams: (stageId: string) => getJson<AdminExamsResponse>(`/api/admin/exams${toSearchParams({ stage_id: stageId })}`),
  examAttempts: (examId: string, filters: AdminExamAttemptFilters) => getJson<AdminExamAttemptsResponse>(`/api/admin/exams/${examId}/attempts${toSearchParams(filters)}`),
  examAttempt: (examId: string, attemptId: string) => getJson<AdminExamAttemptDetailResponse>(`/api/admin/exams/${examId}/attempts/${attemptId}`),
  updateExamAttemptScore: (examId: string, attemptId: string, payload: { total_score: number; reason: string }) => patchJson<AdminExamAttemptScoreResponse>(`/api/admin/exams/${examId}/attempts/${attemptId}/score`, payload, { headers: requestHeaders() }),
  missingSubmissions: (stageId: string, filters: AdminMissingSubmissionFilters) => getJson<AdminMissingSubmissionsResponse>(`/api/admin/stages/${stageId}/missing-submissions${toSearchParams(filters)}`),
  submissions: (stageId: string, filters: AdminSubmissionFilters) => getJson<AdminSubmissionsResponse>(`/api/admin/stages/${stageId}/submissions${toSearchParams(filters)}`),
  submission: (submissionId: string) => getJson<AdminSubmissionResponse>(`/api/admin/submissions/${submissionId}`),
  reviewSubmission: (submissionId: string, payload: AdminSubmissionReviewPayload) => postJson<AdminSubmissionResponse>(`/api/admin/submissions/${submissionId}/review`, payload, { headers: requestHeaders() }),
  advancement: (stageId: string, batchId?: string) => getJson<AdminAdvancementResponse>(`/api/admin/stages/${stageId}/advancement${toSearchParams({ batch_id: batchId })}`),
}
